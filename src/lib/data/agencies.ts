export async function getAgencyBySlug(slug: string): Promise<AgencyWithRelations | undefined> {
  const agency = agencies.find((a) => a.slug === slug);
  if (!agency) return undefined;
  const agencyEmployees = employees.filter((e) => e.agency_id === agency.id && e.status === "published");
  const reviewCount = agencyEmployees.reduce((sum, e) => sum + e.review_count, 0);
  const avgRating =
    agencyEmployees.length > 0
      ? Math.round(
          (agencyEmployees.reduce((sum, e) => sum + e.avg_rating * e.review_count, 0) /
            Math.max(reviewCount, 1)) *
            10
        ) / 10
      : 0;
  return { ...agency, employees: agencyEmployees, reviewCount, avgRating };
}

export async function getFeaturedAgencies(): Promise<Agency[]> {
  return agencies.filter((a) => a.status === "approved" && a.is_featured);
}
