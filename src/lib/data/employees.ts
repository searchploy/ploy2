export async function getEmployeesByDepartment(department: string) {
  return employees.filter((e) => e.department === department);
}

export async function getEmployeesByIndustry(industry: string) {
  return employees.filter((e) => e.industries.includes(industry));
}

export async function getEmployeesByDepartmentAndIndustry(
  department: string | null,
  industry: string | null
) {
  return employees.filter((e) => {
    const matchesDept = !department || e.department === department;
    const matchesIndustry = !industry || e.industries.includes(industry);
    return matchesDept && matchesIndustry;
  });
}

export async function getEmployeesByAgency(agencyId: string) {
  return employees.filter((e) => e.agency_id === agencyId);
}

